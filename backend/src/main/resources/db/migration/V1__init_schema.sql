CREATE TABLE app_config (
    config_key VARCHAR(255) PRIMARY KEY,
    config_value VARCHAR(255) NOT NULL
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(255) NOT NULL,
    last_name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    email_verified BOOLEAN NOT NULL,
    phone_verified BOOLEAN NOT NULL,
    password VARCHAR(255),
    provider VARCHAR(255),
    provider_id VARCHAR(255),
    phone VARCHAR(255),
    role VARCHAR(255) NOT NULL,
    created_date TIMESTAMP,
    modified_date TIMESTAMP
);

CREATE TABLE addresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    address_type VARCHAR(255) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    street_address VARCHAR(255) NOT NULL,
    landmark VARCHAR(255),
    city VARCHAR(255) NOT NULL,
    state VARCHAR(255) NOT NULL,
    pincode VARCHAR(255) NOT NULL,
    country VARCHAR(255) NOT NULL,
    phone VARCHAR(255),
    is_primary BOOLEAN NOT NULL,
    CONSTRAINT fk_user_address FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    category VARCHAR(255) NOT NULL,
    price DOUBLE PRECISION NOT NULL,
    original_price DOUBLE PRECISION,
    image TEXT,
    description TEXT NOT NULL,
    fabric VARCHAR(255) NOT NULL,
    weave VARCHAR(255) NOT NULL,
    color VARCHAR(255) NOT NULL,
    rating DOUBLE PRECISION NOT NULL,
    reviews INT NOT NULL,
    badge VARCHAR(255),
    created_date TIMESTAMP,
    modified_date TIMESTAMP
);

CREATE TABLE product_images (
    product_id BIGINT NOT NULL,
    image_url TEXT,
    CONSTRAINT fk_product_images FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
);

CREATE TABLE recent_views (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    product_id BIGINT NOT NULL,
    viewed_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_recent_views_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
);

CREATE TABLE contact_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    email VARCHAR(255),
    phone VARCHAR(255),
    subject VARCHAR(255),
    message TEXT,
    created_date TIMESTAMP
);

CREATE TABLE social_media_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    platform VARCHAR(255) NOT NULL UNIQUE,
    url VARCHAR(255) NOT NULL,
    announcement TEXT
);
